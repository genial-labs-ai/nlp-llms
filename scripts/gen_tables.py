def scaffold_lectures(v: dict) -> None:
    for key, m in modules_in_order(v):
        page = ROOT / "lectures" / f"{m['slug']}.qmd"
        if not page.exists():
            page.parent.mkdir(exist_ok=True)
            page.write_text(LECTURE_STUB.format(key=key, n=m["n"]), encoding="utf-8")


def main() -> None:
    v = load_variables()
    write(INCLUDES / "facts.md", facts_strip(v))
    write(INCLUDES / "days.md", days_cards(v))
    write(INCLUDES / "path.md", path_steps(v))
    write(INCLUDES / "schedule.md", schedule(v))
    write(INCLUDES / "module-shape.md", module_shape(v))
    for d in days_in_order(v):
        write(INCLUDES / f"day-{d['n']}.md", day_cards(v, d))
    for key, m in modules_in_order(v):
        write(INCLUDES / f"module-{m['n']:02d}.md", module_block(v, key, m))
        lecture = live_plan.read(m["slug"])
        live, pace = INCLUDES / f"live-{m['n']:02d}.md", INCLUDES / f"pace-{m['n']:02d}.md"
        if lecture["front"].get("live"):
            notice = LIVE_NOTICE.format(slug=m["slug"])
            write(live, live_plan.table(m["slug"], lecture), notice)
            write(pace, live_plan.pace_rows(m["slug"], lecture), notice)
        else:
            # A plan that was removed must not leave its old tables on the page.
            live.unlink(missing_ok=True)
            pace.unlink(missing_ok=True)
    write(INCLUDES / "notebooks.md", notebooks_index(v))
    records = run_records.load_valid(set(v["readiness"]["envs"]))
    report = readiness.build(v, records)
    write(INCLUDES / "readiness-summary.md", readiness_summary(report))
    write(INCLUDES / "readiness.md", readiness_table(v, report))
    sidebar = INCLUDES / "sidebar.yml"
    sidebar.write_text(f"{YAML_NOTICE}\n{sidebar_yaml(v)}", encoding="utf-8")
    replace_region(ROOT / "README.md", "status", readme_status(v, report))
    replace_region(ROOT / "README.md", "modules", readme_table(v))
    replace_region(ROOT / "README.md", "days", readme_days(v))
    scaffold_lectures(v)


if __name__ == "__main__":
    main()
