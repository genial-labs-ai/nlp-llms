def readme_days(v: dict) -> str:
    """The days, their themes and modules, and how long a module is."""
    rows = ["| Day | Theme | Modules |", "|---|---|---|"]
    if prework(v):
        numbers = ", ".join(str(m["n"]) for _, m in prework(v))
        rows.append(f"| Before Day 1 | Pre-work (optional) | {numbers} |")
    for d in days_in_order(v):
        n = [m["n"] for _, m in day_modules(v, d)]
        rows.append(f"| {d['n']} | {d['title']} | {n[0]}–{n[-1]} |")
    schedule_link = f"The [schedule]({v['repo']['site_url']}/schedule.html) has the times."
    return "\n".join(rows) + f"\n\n{module_shape(v)} {schedule_link}"


def replace_region(path: Path, name: str, body: str) -> None:
    begin, end = f"<!-- BEGIN {name} -->", f"<!-- END {name} -->"
    text = path.read_text(encoding="utf-8")
    if begin not in text or end not in text:
        raise SystemExit(f"{path.name}: missing {begin} / {end} markers")
    head, rest = text.split(begin, 1)
    _, tail = rest.split(end, 1)
    path.write_text(f"{head}{begin}\n{body.rstrip()}\n{end}{tail}", encoding="utf-8")


