"""Write the generated Markdown from _variables.yml.

Outputs (all overwritten on every run, never edited by hand):
  _includes/facts.md         the counts under the landing page's hero
  _includes/days.md          the days as cards
  _includes/path.md          the module arc on the landing page
  _includes/schedule.md      the timetable: one grid for each run of days on the same clock
  _includes/module-shape.md  one paragraph: how long a module is on each clock
  _includes/day-N.md         the module cards for one day
  _includes/module-NN.md     the header block of one lecture page
  _includes/notebooks.md     the notebook index with Colab links
  _includes/readiness.md     the readiness page: evidence per module, blocking work
  _includes/readiness-summary.md  the one-paragraph status on the landing, FAQ and teach pages
  _includes/sidebar.yml      the module sidebar, read by _quarto.yml (metadata-files)
  README.md                  the regions between the BEGIN/END status, modules and days markers

It also creates a stub lecture page for any module that has none. Existing
lecture pages are never touched.

The readiness outputs read modules.mNN.readiness and readiness: in _variables.yml and the
run records in runs/ (scripts/readiness.py). They print dates from the records, never today's
date, so they change only when the repository does.

Each day runs on a named clock (schedule.clocks). The clock's module units take the
day's `slots` in order (placements()). A unit is one `module` slot, or a `part: lecture`
slot with the `part: lab` slot after it, so a module can span lunch. A module that fills
one unit has the clock's lecture/lab/debrief shape; one that fills several (the
capstone) is shown as hands-on.

Module numbers start at 0. Module 0 is pre-work (`day: 0`) with `notebook: false`: it
gets a lecture page, a pre-work step on the landing path and in the sidebar, and a
README row, but no module slot and no row in the notebook index. A day's optional
`clinic` (drop-in help with Module 0) fills its clock's `clinic` slot.

Run:  uv run --group site python scripts/gen_tables.py
"""

