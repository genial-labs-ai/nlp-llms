ROOT = Path(__file__).resolve().parent.parent
INCLUDES = ROOT / "_includes"
NOTICE = "<!-- GENERATED by scripts/gen_tables.py from _variables.yml. Do not edit by hand. -->"
# The live plan and pace rows come from a lecture's front matter, not _variables.yml.
LIVE_NOTICE = (
    "<!-- GENERATED by scripts/gen_tables.py from the `live:` front matter of"
    " lectures/{slug}.qmd. Do not edit by hand. -->"
)
YAML_NOTICE = "# GENERATED by scripts/gen_tables.py from _variables.yml. Do not edit by hand."
BADGE = "https://colab.research.google.com/assets/colab-badge.svg"
NO_NOTEBOOK = "No notebook: runs in your terminal"
PREWORK = "Before Day 1 · Pre-work"


def load_variables() -> dict:
    return yaml.safe_load((ROOT / "_variables.yml").read_text(encoding="utf-8"))


def modules_in_order(v: dict) -> list[tuple[str, dict]]:
    return sorted(v["modules"].items(), key=lambda kv: kv[1]["n"])


def days_in_order(v: dict) -> list[dict]:
    return sorted(v["days"].values(), key=lambda d: d["n"])


def notebook_exists(slug: str) -> bool:
    return (ROOT / "notebooks" / f"{slug}.ipynb").exists()


def has_notebook(m: dict) -> bool:
    return m.get("notebook", True)


def colab_badge(v: dict, slug: str) -> str:
    """A Colab badge if the notebook exists, otherwise a plain note."""
    if not notebook_exists(slug):
        return "In preparation"
    return f"[![Open in Colab]({BADGE})]({v['repo']['colab_base']}/{slug}.ipynb)"


def lab_cell(v: dict, m: dict) -> str:
    return colab_badge(v, m["slug"]) if has_notebook(m) else NO_NOTEBOOK


def slot_parts(slot) -> tuple[str, str | None]:
    """A day slot is a module key, or {module, label} to override the label."""
    if isinstance(slot, dict):
        return slot["module"], slot.get("label")
    return slot, None


def write(path: Path, body: str, notice: str = NOTICE) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"{notice}\n\n{body.rstrip()}\n", encoding="utf-8")


def clock(minutes: int) -> str:
    return f"{minutes // 60:02d}:{minutes % 60:02d}"


def to_minutes(hhmm: str) -> int:
    return int(hhmm[:2]) * 60 + int(hhmm[3:])


def span(slot: dict) -> int:
    """A slot's length in minutes."""
    return to_minutes(slot["end"]) - to_minutes(slot["start"])


def clock_of(v: dict, day: dict) -> dict:
    return v["schedule"]["clocks"][day["clock"]]


def units(clk: dict) -> list[list[dict]]:
    """The clock's module units, in order. A unit is one `module` slot, or a
    `part: lecture` slot together with the `part: lab` slot that follows it."""
    out, pending = [], None
    for s in clk["slots"]:
        if s["kind"] != "module":
            continue
        part = s.get("part")
        if part is None and pending is None:
            out.append([s])
        elif part == "lecture" and pending is None:
            pending = [s]
        elif part == "lab" and pending is not None:
            out.append(pending + [s])
            pending = None
        else:
            raise ValueError(f"slot {s['start']}: `part: lab` must close a `part: lecture` slot")
    if pending is not None:
        raise ValueError(f"slot {pending[0]['start']}: `part: lecture` with no `part: lab`")
    return out


def placements(v: dict, day: dict) -> list[dict]:
    """The day's `slots` matched to its clock's units, in order: one dict per unit
    with the module `key`, its `label` (or None) and the unit's clock `slots`."""
    return [
        {"key": key, "label": label, "slots": unit}
        for (key, label), unit in zip(
            (slot_parts(s) for s in day["slots"]), units(clock_of(v, day)), strict=True
        )
    ]


def module_placements(v: dict, key: str) -> list[tuple[dict, dict]]:
    """(day, placement) for each unit that module `key` fills. Empty for pre-work."""
    return [(d, p) for d in days_in_order(v) for p in placements(v, d) if p["key"] == key]


def minutes_of(v: dict, key: str) -> int:
    """The minutes the clocks give module `key` (0 for pre-work)."""
    return sum(span(s) for _, p in module_placements(v, key) for s in p["slots"])


def shape(v: dict, key: str) -> dict | None:
    """{lecture, lab[, debrief]} minutes for a module that fills exactly one unit.
    None for pre-work and for a module that fills several (the capstone is hands-on)."""
    found = module_placements(v, key)
    return clock_of(v, found[0][0])["shape"] if len(found) == 1 else None


def is_prework(m: dict) -> bool:
    return m["day"] == 0


def prework(v: dict) -> list[tuple[str, dict]]:
    return [(key, m) for key, m in modules_in_order(v) if is_prework(m)]


def clinic_of(v: dict, key: str) -> tuple[dict, dict] | None:
    """(day, slot) if module `key` fills a day's optional clinic slot."""
    for d in days_in_order(v):
        if d.get("clinic") and slot_parts(d["clinic"])[0] == key:
            return d, next(s for s in clock_of(v, d)["slots"] if s["kind"] == "clinic")
    return None


def module_clock(v: dict, key: str) -> str:
    """'09:10–10:45', or one range per stretch of a module that spans a break:
    '11:30–12:25 · 13:25–14:30'. Pre-work gives its clinic's time."""
    ranges: list[list[str]] = []
    for _, p in module_placements(v, key):
        for s in p["slots"]:
            if ranges and ranges[-1][1] == s["start"]:
                ranges[-1][1] = s["end"]
            else:
                ranges.append([s["start"], s["end"]])
    if not ranges:
        found = clinic_of(v, key)
        return f"{found[1]['start']}–{found[1]['end']}" if found else ""
    return " · ".join(f"{a}–{b}" for a, b in ranges)


def shape_text(s: dict) -> str:
    """'45 lecture, 50 lab' or '55 lecture, 55 lab, 10 debrief'."""
    return ", ".join(f"{minutes} {part}" for part, minutes in s.items())


def timing(v: dict, key: str, m: dict) -> str:
    """'120 minutes (55 lecture, 55 lab, 10 debrief)'. Also used for notebook headers."""
    if is_prework(m):
        found = clinic_of(v, key)
        if not found:
            return f"{m['minutes']} minutes, pre-work"
        clinic = f"optional clinic on Day {found[0]['n']}, {module_clock(v, key)}"
        return f"{m['minutes']} minutes, pre-work; {clinic}"
    s = shape(v, key)
    if s:
        return f"{m['minutes']} minutes ({shape_text(s)})"
    return f"{m['minutes']} minutes"


def colab_button(v: dict, m: dict, text: str = "Open in Colab") -> str:
    """A styled link to the lab (site pages only; README keeps the image badge)."""
    if not has_notebook(m):
        return f"[{NO_NOTEBOOK}]{{.lab-note}}"
    if not notebook_exists(m["slug"]):
        return "[Lab in preparation]{.lab-note}"
    return f"[{text}]({v['repo']['colab_base']}/{m['slug']}.ipynb){{.btn-colab}}"


def chips(items: list[str]) -> str:
    return " ".join(f"[{item}]{{.chip}}" for item in items)


def day_modules(v: dict, day: dict) -> list[tuple[str, dict]]:
    """The day's modules in order, each once (the capstone fills two units)."""
    keys = list(dict.fromkeys(p["key"] for p in placements(v, day)))
    return [(key, v["modules"][key]) for key in keys]


def clock_groups(v: dict) -> list[tuple[str, list[dict]]]:
    """The days on each clock, in order of first use: [(clock name, [day, ...]), ...].
    Days on one clock share one timetable grid even when they are not consecutive."""
    groups: dict[str, list[dict]] = {}
    for d in days_in_order(v):
        groups.setdefault(d["clock"], []).append(d)
    return list(groups.items())


def days_label(days: list[dict], prose: bool = False) -> str:
    """'Day 1', 'Days 2–5' (or 'Days 2 to 5' in a sentence)."""
    if len(days) == 1:
        return f"Day {days[0]['n']}"
    dash = " to " if prose else "–"
    return f"Days {days[0]['n']}{dash}{days[-1]['n']}"


ORDINALS = ["first", "second", "third", "fourth", "fifth", "sixth"]


def shape_prose(s: dict) -> str:
    """'45 minutes of lecture, then 50 of lab' (a debrief reads 'a 10-minute debrief')."""
    parts = []
    for i, (part, minutes) in enumerate(s.items()):
        if part == "debrief":
            parts.append(f"a {minutes}-minute debrief")
        else:
            parts.append(f"{minutes} minutes of {part}" if i == 0 else f"{minutes} of {part}")
    return ", ".join(parts[:-1]) + ", then " + parts[-1]


def split_sentences(v: dict, clk: dict, days: list[dict]) -> list[str]:
    """One sentence per unit that a break splits: between a module's lecture and its lab,
    or across a hands-on unit (the capstone) that has neither."""
    out = []
    slots = clk["slots"]
    for i, unit in enumerate(units(clk)):
        if len(unit) < 2:
            continue
        between = slots[slots.index(unit[0]) + 1 : slots.index(unit[1])]
        label = " and ".join(s["label"].lower() for s in between)
        placed = [(d, placements(v, d)[i]) for d in days]
        taught = [d for d, p in placed if shape(v, p["key"])]
        hands_on = [(d, p) for d, p in placed if not shape(v, p["key"])]
        if taught:
            who = "those days" if len(taught) == len(days) else days_label(taught, prose=True)
            out.append(
                f"On {who} the {ORDINALS[i]} module breaks for {label}"
                " between its lecture and its lab."
            )
        for d, p in hands_on:
            title = p["label"] or v["modules"][p["key"]]["title"]
            out.append(
                f"On Day {d['n']}, the {title.lower().replace(': ', ' ')} runs on across {label}."
            )
    return out


def module_shape(v: dict) -> str:
    """How long a module is on each clock, as one short paragraph."""
    sentences = []
    for name, days in clock_groups(v):
        s = v["schedule"]["clocks"][name]["shape"]
        sentences.append(
            f"On {days_label(days, prose=True)}, each module is {sum(s.values())} minutes:"
            f" {shape_prose(s)}."
        )
        sentences += split_sentences(v, v["schedule"]["clocks"][name], days)
    for key, m in modules_in_order(v):
        found = module_placements(v, key)
        if len(found) > 1:
            day_numbers = sorted({d["n"] for d, _ in found})
            where = " and ".join(f"Day {n}" for n in day_numbers)
            sentences.append(
                f"The {m['title'].lower()} (Module {m['n']}) has no lecture: it takes"
                f" {prose_times(module_clock(v, key))} on {where}."
            )
    return " ".join(sentences)


def prose_times(ranges: str) -> str:
    """'11:30–12:25 · 13:25–14:30 · 14:45–16:45' as '11:30–12:25, 13:25–14:30 and 14:45–16:45'."""
    parts = ranges.split(" · ")
    return parts[0] if len(parts) == 1 else ", ".join(parts[:-1]) + " and " + parts[-1]


def minute_range(values: list[int]) -> str:
    lo, hi = min(values), max(values)
    return str(lo) if lo == hi else f"{lo}–{hi}"


def facts_strip(v: dict) -> str:
    w = v["workshop"]
    taught = [m for m in v["modules"].values() if not is_prework(m)]
    labs = sum(1 for m in v["modules"].values() if has_notebook(m)) + 1  # plus 00-setup
    shapes = [v["schedule"]["clocks"][name]["shape"] for name, _ in clock_groups(v)]
    facts = [
        f"**{w['days']}** days",
        f"**{len(taught)}** modules",
        f"**{labs}** Colab notebooks",
        f"**{minute_range([s['lecture'] for s in shapes])}** min lectures,"
        f" **{minute_range([s['lab'] for s in shapes])}** min labs",
    ]
    debriefs = [s["debrief"] for s in shapes if s.get("debrief")]
    if debriefs:
        facts.append(f"**{minute_range(debriefs)}** min lab debriefs")
    return "::: {.facts}\n" + "\n".join(f"[{f}]{{.fact}}" for f in facts) + "\n:::"


def days_cards(v: dict) -> str:
    out = ["::: {.day-grid}"]
    for d in days_in_order(v):
        taught = [m["n"] for _, m in day_modules(v, d)]
        span_text = f"Modules {taught[0]}–{taught[-1]}"
        out += [
            "::: {.day-card}",
            f"[Day {d['n']}]{{.eyebrow}}",
            "",
            f"[{d['title']}](day-{d['n']}.qmd){{.day-card-title}}",
            "",
            f"[{d['question']}]{{.day-card-question}}",
            "",
            f"[{span_text}]{{.day-card-span}}",
            ":::",
        ]
    out.append(":::")
    return "\n".join(out)


def path_steps(v: dict) -> str:
    """The module arc for the landing page: pre-work, then one step per module by day."""
    groups = []
    if prework(v):
        groups.append((f"[{PREWORK}](setup.qmd#module-0){{.path-day-label}}", prework(v), True))
    for d in days_in_order(v):
        label = f"[Day {d['n']} · {d['short']}](day-{d['n']}.qmd){{.path-day-label}}"
        groups.append((label, day_modules(v, d), False))
    out = ["::: {.path}"]
    for label, mods, optional in groups:
        out += ["::: {.path-day}", label, ""]
        for _, m in mods:
            tag = " [Optional pre-work]{.chip}" if optional else ""
            out += [
                "::: {.path-step" + (" .path-step-optional" if optional else "") + "}",
                f"[{m['n']}]{{.path-num}}",
                "",
                "::: {.path-body}",
                f"[{m['title']}](lectures/{m['slug']}.qmd){{.path-title}}{tag}",
                "",
                m["summary"],
                ":::",
                ":::",
            ]
        out.append(":::")
    out.append(":::")
    return "\n".join(out)


def segments(s: dict, slot: dict) -> list[tuple[str, str, int]]:
    """(part, start time, minutes) for the parts of shape `s` that fall in this slot:
    all of them, or the lecture alone (`part: lecture`), or the rest (`part: lab`)."""
    parts = list(s.items())
    if slot.get("part") == "lecture":
        parts = parts[:1]
    elif slot.get("part") == "lab":
        parts = parts[1:]
    t, out = to_minutes(slot["start"]), []
    for part, minutes in parts:
        out.append((part, clock(t), minutes))
        t += minutes
    return out


def bar(segs: list[tuple[str, str, int]]) -> str:
    """The bar under a module: one span per part, each as wide as its minutes."""
    out = []
    for part, start, minutes in segs:
        text = f"{part.capitalize()} {start}"
        grow = f'style="flex-grow: {minutes}"'
        if part == "debrief":
            # Too narrow for its label: the text is for screen readers and the tooltip.
            out.append(f'[[{text}]{{.visually-hidden}}]{{.slot-debrief {grow} title="{text}"}}')
        else:
            out.append(f"[{text}]{{.slot-{part} {grow}}}")
    return "[" + "".join(out) + "]{.slot-split}"


def module_cell(v: dict, p: dict, slot: dict) -> str:
    m = v["modules"][p["key"]]
    cell = f"[{m['n']} · {p['label'] or m['title']}](lectures/{m['slug']}.qmd){{.slot-module}}"
    s = shape(v, p["key"])
    hands_on = "[[Hands-on]{.slot-lab}]{.slot-split}"  # the capstone: no lecture/lab split
    return f"{cell} {bar(segments(s, slot)) if s else hands_on}"


def schedule_grid(v: dict, name: str, days: list[dict]) -> str:
    """One timetable for days that share a clock. A plain pipe table: spans carry the
    classes custom.scss uses to tell lecture, lab, debrief, break and clinic apart."""
    clk = v["schedule"]["clocks"][name]
    head = "| Time | " + " | ".join(f"[Day {d['n']}](day-{d['n']}.qmd) {d['short']}" for d in days)
    rows = [head + " |", "|---|" + "---|" * len(days)]
    # Each day's placement for each of the clock's module slots, in clock order.
    owner = {d["n"]: [p for p in placements(v, d) for _ in p["slots"]] for d in days}
    i = 0
    for slot in clk["slots"]:
        cells = []
        for d in days:
            kind = slot["kind"]
            if kind in ("opening", "closing"):
                cells.append(f"[{d[kind]}]{{.slot-{kind}}}")
            elif kind == "clinic":
                if d.get("clinic"):
                    key, label = slot_parts(d["clinic"])
                    m = v["modules"][key]
                    link = f"lectures/{m['slug']}.qmd"
                    cells.append(f"[{label or m['title']}]({link}){{.slot-clinic}}")
                else:
                    cells.append("")
            elif kind == "break":
                cells.append(f"[{slot['label']}]{{.slot-break}}")
            else:
                cells.append(module_cell(v, owner[d["n"]][i], slot))
        if slot["kind"] == "module":
            i += 1
        rows.append(f"| {slot['start']}–{slot['end']} | " + " | ".join(cells) + " |")
    return "\n".join(rows)


def schedule(v: dict) -> str:
    """The timetable: one grid for each run of days on the same clock."""
    out = []
    for name, days in clock_groups(v):
        minutes = sum(v["schedule"]["clocks"][name]["shape"].values())
        out += [
            f"## {days_label(days)} · {minutes}-minute modules {{#clock-{name}}}",
            "",
            f"::: {{.table-wide .timetable .days-{len(days)}}}",
            schedule_grid(v, name, days),
            ":::",
            "",
        ]
    return "\n".join(out)


def card(v: dict, key: str, m: dict, eyebrow: str, optional: bool = False) -> list[str]:
    """One module card: its clock time (a line per stretch), title, summary, actions."""
    return [
        "::: {.module-card" + (" .module-card-optional" if optional else "") + "}",
        "::: {.module-card-time}",
        module_clock(v, key).replace(" · ", "\\\n"),
        ":::",
        "",
        "::: {.module-card-body}",
        f"[{eyebrow}]{{.eyebrow}}",
        "",
        f"[{m['title']}](lectures/{m['slug']}.qmd){{.module-card-title}}",
        "",
        m["summary"],
        "",
        "::: {.module-card-actions}",
        f"[Read the lecture](lectures/{m['slug']}.qmd){{.btn-quiet}} {colab_button(v, m)} "
        + chips(m["stack"]),
        ":::",
        ":::",
        ":::",
    ]


def day_cards(v: dict, day: dict) -> str:
    """One card per module of the day, with its clock time; the clinic first, if any."""
    out = ["::: {.module-cards}"]
    if day.get("clinic"):
        key, _ = slot_parts(day["clinic"])
        m = v["modules"][key]
        out += card(v, key, m, f"Module {m['n']} · pre-work, optional clinic", optional=True)
    for key, m in day_modules(v, day):
        out += card(v, key, m, f"Module {m['n']}")
    out.append(":::")
    return "\n".join(out)


def module_block(v: dict, key: str, m: dict) -> str:
    """The header of a lecture page. Links are project-absolute: the including page
    sits in lectures/."""
    if is_prework(m):
        where = f"[{PREWORK}](/setup.qmd#module-0){{.module-day}}"
    else:
        day = next(d for d in v["days"].values() if d["n"] == m["day"])
        where = f"[Day {m['day']} · {day['short']}](/day-{m['day']}.qmd){{.module-day}}"
    lines = [
        "::: {.module-header}",
        "::: {.module-meta}",
        f"{where} [Module {m['n']}]{{.module-num}} [{timing(v, key, m)}]{{.module-time}}",
        ":::",
        "",
        "::: {.module-summary}",
        m["summary"],
        ":::",
        "",
        "::: {.module-actions}",
        f"{colab_button(v, m, 'Open the lab in Colab')} {chips(m['stack'])}",
        ":::",
        ":::",
        "",
        "::: {.objectives}",
        "## Learning objectives",
        "",
        "By the end of this module you can:",
        "",
    ]
    lines += [f"- {o}" for o in m["objectives"]]
    lines.append(":::")
    return "\n".join(lines)


def notebooks_index(v: dict) -> str:
    s = v["setup"]
    out = [
        "::: {.module-cards}",
        "::: {.module-card}",
        "::: {.module-card-time}",
        "Before Day 1",
        ":::",
        "",
        "::: {.module-card-body}",
        f"[Start here · {s['minutes']} minutes]{{.eyebrow}}",
        "",
        f"[{s['title']}]{{.module-card-title}}",
        "",
        s["summary"],
        "",
        "::: {.module-card-actions}",
        colab_button(v, {"slug": s["slug"]}),
        ":::",
        ":::",
        ":::",
        ":::",
    ]
    for d in days_in_order(v):
        labs = [m for _, m in day_modules(v, d) if has_notebook(m)]
        out += [
            "",
            f"## Day {d['n']} · {d['short']} {{#day-{d['n']}}}",
            "",
            "::: {.notebook-table}",
            "| # | Notebook | Lecture | Lab |",
            "|---|---|---|---|",
        ]
        for m in labs:
            out.append(
                f"| {m['n']} | **{m['title']}** [{m['summary']}]{{.notebook-summary}} "
                f"| [Lecture {m['n']}](lectures/{m['slug']}.qmd) | {colab_button(v, m)} |"
            )
        out.append(":::")
    return "\n".join(out)


def sidebar_yaml(v: dict) -> str:
    """website.sidebar for _quarto.yml (read through metadata-files): the modules
    grouped by day, pre-work first. Quarto shows it on the pages it lists and derives
    the previous/next links at the foot of each lecture from the same order."""
    groups = [(PREWORK, prework(v))] if prework(v) else []
    groups += [(f"Day {d['n']} · {d['short']}", day_modules(v, d)) for d in days_in_order(v)]
    sections = [
        {
            "section": title,
            "contents": [
                {"href": f"lectures/{m['slug']}.qmd", "text": f"{m['n']} · {m['title']}"}
                for _, m in mods
            ],
        }
        for title, mods in groups
    ]
    sidebar = {"id": "modules", "title": "Modules", "style": "floating", "contents": sections}
    return yaml.safe_dump(
        {"website": {"sidebar": [sidebar]}}, sort_keys=False, allow_unicode=True, width=1000
    )


def readiness_status(report: dict) -> str:
    """One paragraph: is the workshop ready to teach, and what has run where."""
    s = report["summary"]
    verdict = "ready to teach" if s["ready"] else "not yet ready to teach"
    when = f"As of {s['as_of']}" if s["as_of"] else "No runs are recorded yet"
    parts = [
        f"**{when}: {verdict}.**",
        f"{s['teaching']} of {s['labs']} labs have run end to end, with their current code,"
        " on the Colab runtime they are designed for.",
        f"{s['real']} have run end to end on their real path elsewhere, on another machine"
        " or on the CI runner"
        + (f" ({s['real_quick']} of them only with QUICK settings)" if s["real_quick"] else "")
        + f", and {s['real_partial_only']} more in part.",
    ]
    if s["ci_to"]:
        span = s["ci_to"] if s["ci_from"] == s["ci_to"] else f"{s['ci_from']} to {s['ci_to']}"
        failed = f", {s['ci_failed']} failed" if s["ci_failed"] else ""
        if s["ci_stale"]:
            failed += f", {s['ci_stale']} last ran before their code changed"
        parts.append(
            f"On the GitHub CPU runner (newest run of each notebook, {span}),"
            f" {s['ci_passed']} of {s['notebooks']} notebooks passed{failed};"
            f" {s['ci_doubles']} of the passing runs used test doubles, which check that the"
            " code runs, not what the models do."
        )
    parts.append(f"{s['items_open']} of {s['items']} pieces of blocking work are open.")
    return " ".join(parts)


def readiness_summary(report: dict) -> str:
    return readiness_status(report) + " [What has run, where, and what is missing](/readiness.qmd)."


def _accounts(r: dict) -> str:
    text = ", ".join(r["accounts"])
    if r.get("optional_accounts"):
        text += f"; optional: {', '.join(r['optional_accounts'])}"
    if r["cost"] == "free":
        return f"{text}. Free"
    return f"{text}. {r['cost'][0].upper()}{r['cost'][1:]}"


def _evidence_cell(v: dict, e: dict) -> str:
    def show(r):
        return readiness.describe(v, r) if r is not None else "not run"

    ci = e["ci"]
    if ci is None:
        ci_text = "—"
    elif ci["path"] == "offline":
        ci_text = show(ci) + ", with test doubles"
    else:
        ci_text = show(ci) + ", real path (no test doubles)"
    return "<br>".join(
        [
            "**On its Colab runtime:** " + show(e["teaching"]),
            "**Real path, other runs:** " + show(e["other"]),
            "**CI:** " + ci_text,
        ]
    )


def readiness_table(v: dict, report: dict) -> str:
    """The full readiness page: one row per module, the open work, and a legend."""
    R = v["readiness"]
    envs = R["envs"]
    rows = [
        "| Module | Content | Designed for | Evidence | Without API keys | Accounts and cost |",
        "|---|---|---|---|---|---|",
    ]
    for _, m in modules_in_order(v):
        r = m["readiness"]
        content = f"Lecture {r['lecture']}" + (f" · lab {r['lab']}" if r["lab"] != "none" else "")
        planned = f"{envs[r['runtime']]['name']} · estimate {r['estimate_minutes']} min"
        if has_notebook(m):
            evidence = _evidence_cell(v, report["evidence"][m["slug"]])
        else:
            evidence = "No notebook. Not yet run on a fresh laptop"
        fallback = readiness.FALLBACK_LABELS[r["fallback"]["kind"]]
        rows.append(
            f"| [{m['n']} · {m['title']}](/lectures/{m['slug']}.qmd) | {content} | {planned} "
            f"| {evidence} | **{fallback}.** {r['fallback']['note']} | {_accounts(r)} |"
        )
    out = [
        readiness_status(report),
        "",
        "::: {.column-page .table-wide .readiness-table}",
        "\n".join(rows),
        ":::",
        "",
        "## Blocking work {#open-work}",
        "",
    ]
    for item in report["items"]:
        mods = ", ".join(str(n) for n in item["modules"])
        word = "module" if len(item["modules"]) == 1 else "modules"
        mark = "Done" if item["closed"] else "Open"
        out.append(f"- **{mark}:** {item['title']} ({word} {mods}; {item['why']})")
    out.append("")

    gaps = [m for _, m in modules_in_order(v) if m["readiness"].get("gaps")]
    if gaps:
        out += ["## Known gaps by module {#gaps}", ""]
        out += [f"- **{m['n']} · {m['title']}:** {m['readiness']['gaps']}." for m in gaps]
        out.append("")

    out += [
        "## How to read this page {#legend}",
        "",
        "**Evidence.** Each line is the newest run of that kind, from the run records in"
        " [`runs/`]({{< var repo.url >}}/tree/main/runs). A newer failure replaces an older"
        " pass, and on the same day a failure wins. *On its Colab runtime* means a worked run"
        " (solutions bound) of the whole notebook, on the path a participant without keys"
        " takes, with no QUICK shortcuts, on the runtime the module is designed for, recorded"
        " by a tool with the notebook's code hash; it stops counting when the code changes."
        " *Real path, other runs* is the newest other run without test doubles, on any"
        " machine except the CI runner; a laptop's or a CPU runner's time does not predict a"
        " T4's. *CI* is the newest run on the GitHub CPU runner: with test doubles it shows"
        " that the code runs, not what a model does. A run marked *before the notebook last"
        " changed* was made against older code; backfilled runs carry no code hash, so they"
        " cannot be checked. An estimate is a planning figure from the lab's brief, not a"
        " measurement. Dates are shown as recorded; the release check will also require a"
        f" teaching run to be at most {R['max_run_age_days']} days old.",
        "",
        "**Paths.**",
        "",
    ]
    out += [f"- `{k}`: {text}." for k, text in R["paths"].items()]
    out += ["", "**Without API keys.**", ""]
    out += [
        f"- *{readiness.FALLBACK_LABELS[k]}*: {text}." for k, text in R["fallback_kinds"].items()
    ]
    return "\n".join(out)


def readme_status(v: dict, report: dict) -> str:
    site = v["repo"]["site_url"]
    return f"> {readiness_status(report)} See the [readiness page]({site}/readiness.html)."


def readme_table(v: dict) -> str:
    site = v["repo"]["site_url"]
    rows = ["| # | Day | Module | Lab |", "|---|---|---|---|"]
    for _, m in modules_in_order(v):
        day = "Pre-work" if is_prework(m) else m["day"]
        rows.append(
            f"| {m['n']} | {day} | [{m['title']}]({site}/lectures/{m['slug']}.html) "
            f"| {lab_cell(v, m)} |"
        )
