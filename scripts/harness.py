def _solution_number(call: ast.Call):
    arg = call.args[0] if call.args else None
    return arg.value if isinstance(arg, ast.Constant) else None


def exercises_of(cells: list) -> dict:
    """{exercise: (names...)} from the @workshop.solution(N) decorators and the
    workshop.solution_value(N, "name", ...) calls in the solution cells."""
    out: dict = {}
    for cell in cells:
        if cell.get("cell_type") != "code" or "solution" not in cell.get("metadata", {}).get(
            "tags", []
        ):
            continue
        source = "".join(cell["source"]) if isinstance(cell["source"], list) else cell["source"]
        try:
            tree = ast.parse(source)
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                for dec in node.decorator_list:
                    if (
                        isinstance(dec, ast.Call)
                        and isinstance(dec.func, ast.Attribute)
                        and dec.func.attr == "solution"
                        and isinstance(dec.func.value, ast.Name)
                        and dec.func.value.id == "workshop"
                    ):
                        out.setdefault(_solution_number(dec), []).append(node.name)
            if (
                isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute)
                and node.func.attr == "solution_value"
                and len(node.args) >= 2
                and isinstance(node.args[1], ast.Constant)
            ):
                out.setdefault(_solution_number(node), []).append(node.args[1].value)
    return {n: tuple(names) for n, names in out.items()}


def harness_source(slug: str, content_sha: str, exercises: dict) -> str:
    return (
        HARNESS.replace("__NOTEBOOK__", slug)
        .replace("__CONTENT_SHA__", content_sha)
        .replace("__EXERCISES__", repr(dict(sorted(exercises.items(), key=lambda kv: str(kv[0])))))
        .replace("__SETTINGS__", repr(RECORDED_SETTINGS))
        .replace("__MARKERS__", repr(FALLBACK_MARKERS))
    )
