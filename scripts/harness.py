"""The exercise harness that scripts/gen_notebooks.py writes into every notebook.

Two generated code cells:
  workshop-harness  (after the header)  WORKED_EXAMPLE switch and the `workshop` object
  workshop-summary  (before the footer) whose checkpoints passed on whose code, and a
                                        run record to paste into runs/

The harness keeps the folded solutions from replacing a participant's code:
@workshop.solution(N) stores a reference solution and binds it only in worked mode, and
workshop.checkpoint(N) at the top of a checkpoint cell makes the cell report whether it
checked the participant's code or the reference. See CONTRIBUTING.md.
"""

